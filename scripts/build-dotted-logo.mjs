#!/usr/bin/env node
/**
 * Generate a dotted version of the logo lockup.
 *
 * Masking a dot pattern with the glyph slices every dot that meets an edge,
 * which is why the first attempt looked chewed. Instead the glyph is
 * rasterised, sampled on a grid, and a whole dot is emitted for each cell the
 * artwork actually covers. Nothing is ever clipped.
 *
 * The file keeps fill="currentColor" and is used as a CSS mask rather than an
 * <img>: an <img> cannot inherit colour, so as an image it painted black on
 * navy. Masking the finished dot field clips nothing, because the dots in it
 * are already whole.
 *
 * Two marks come out of this: the full lockup, and the logotype on its own for
 * the footer, where the icon repeated a G that is already in the header and the
 * wordmark alone bleeds edge to edge without it.
 *
 * Run: node scripts/build-dotted-logo.mjs
 * Out: public/brand/logo-horizontal-dotted.svg
 *      public/brand/logo-logotype-dotted.svg
 *      src/lib/dotted-logo.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { chromium } from "playwright";

const MARKS = [
  { name: "DOTTED_LOGO", src: "public/brand/logo-horizontal.svg", out: "public/brand/logo-horizontal-dotted.svg" },
  { name: "DOTTED_LOGOTYPE", src: "public/brand/logo-logotype.svg", out: "public/brand/logo-logotype-dotted.svg" },
];
const ROWS = 24;          // coarse enough that the dots read AS dots, fine
                          // enough that the wordmark still reads
const COVERAGE = 0.42;    // a cell lights up once the artwork covers this much
const DOT = 0.40;         // dot radius as a fraction of cell pitch

const browser = await chromium.launch();
const page = await browser.newPage();
const emitted = [];

for (const MARK of MARKS) {
const svg = readFileSync(MARK.src, "utf8");
const [, vbW, vbH] = svg.match(/viewBox="[\d.\-]+ [\d.\-]+ ([\d.]+) ([\d.]+)"/).map(Number);
const cols = Math.round((vbW / vbH) * ROWS);

// Rasterise well above grid resolution so coverage per cell is accurate.
const SS = 8;
const grid = await page.evaluate(
  async ({ svg, cols, rows, ss, coverage }) => {
    const url = "data:image/svg+xml;base64," + btoa(unescape(encodeURIComponent(svg)));
    const img = new Image();
    img.src = url;
    await img.decode();

    const c = document.createElement("canvas");
    c.width = cols * ss;
    c.height = rows * ss;
    const ctx = c.getContext("2d");
    ctx.drawImage(img, 0, 0, c.width, c.height);
    const { data } = ctx.getImageData(0, 0, c.width, c.height);

    const out = [];
    for (let r = 0; r < rows; r++) {
      const line = [];
      for (let q = 0; q < cols; q++) {
        let hit = 0;
        for (let y = 0; y < ss; y++) {
          for (let x = 0; x < ss; x++) {
            const px = ((r * ss + y) * c.width + (q * ss + x)) * 4;
            if (data[px + 3] > 128) hit++;
          }
        }
        line.push(hit / (ss * ss) >= coverage ? 1 : 0);
      }
      out.push(line);
    }
    return out;
  },
  { svg, cols, rows: ROWS, ss: SS, coverage: COVERAGE },
);

const pitch = 10;
const r = (pitch * DOT).toFixed(2);
const dots = [];
grid.forEach((line, y) =>
  line.forEach((on, x) => {
    if (on) dots.push(`<use href="#d" x="${x * pitch}" y="${y * pitch}"/>`);
  }),
);

const out =
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${cols * pitch} ${ROWS * pitch}" ` +
  `width="${cols * pitch}" height="${ROWS * pitch}" fill="currentColor" ` +
  `data-derived="dot rasterisation of ${MARK.src.split("/").pop()}">` +
  `<defs><circle id="d" cx="${pitch / 2}" cy="${pitch / 2}" r="${r}"/></defs>` +
  dots.join("") +
  `</svg>`;

writeFileSync(MARK.out, out);

emitted.push({ name: MARK.name, src: "/" + MARK.out.replace(/^public\//, ""), cols, ratio: (cols / ROWS).toFixed(4) });
const lit = grid.flat().filter(Boolean).length;
console.log(`  grid ${cols} x ${ROWS}  dots ${lit}/${cols * ROWS}  ${(out.length / 1024).toFixed(0)} KB -> ${MARK.out}`);
}

// Emit the geometry too. The consumer needs the aspect ratio to size its box,
// and a hand-copied number goes stale the moment ROWS changes: it already did,
// leaving the mask letterboxed inside a box 40% too wide.
writeFileSync(
  "src/lib/dotted-logo.ts",
  `/** Generated by scripts/build-dotted-logo.mjs. Do not edit. */\n` +
    emitted
      .map(
        (m) =>
          `export const ${m.name} = {\n` +
          `  src: "${m.src}",\n` +
          `  cols: ${m.cols},\n` +
          `  rows: ${ROWS},\n` +
          `  /** width / height of the generated field. */\n` +
          `  ratio: ${m.ratio},\n` +
          `} as const;\n`,
      )
      .join("\n"),
);

await browser.close();
