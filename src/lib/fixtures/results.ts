/**
 * Group-scoped results (§3.1) — keyed Cycle × Sub-category × Tier × Entry.
 *
 * Coverage this set is built to exercise:
 *  - MULTI-MEDAL: e-101 takes Gold in Brand Identity Redesign and Bronze in
 *    Logo Design from a single vote pool (a deliberate consequence of §1.2).
 *  - FULL PODIUM PER TIER: every finalized tier awards Gold, Silver and Bronze,
 *    so the three levels are all represented in Students, Freelancers and
 *    Corporate. Students needed a third group for it - see below.
 *  - THIN GROUP (partial medals): only two Cadets in Calligraphy × Students,
 *    so Gold and Silver are awarded and Bronze simply is not.
 *  - THIN GROUP (withheld): a sole zero-vote Cadet in Book Design × Students,
 *    where Admin withheld the medal from the review screen.
 *  - TIEBREAK: e-106 and e-107 tie on votes; the jury final score decides,
 *    with checkout time as the next tiebreak. The trace is stored.
 *  - DID NOT PLACE: a shortlisted entry that ranked outside the medals.
 *
 * Active-cycle records are PROPOSED rankings from live vote counts with
 * `finalized: false` — that is exactly what the Admin review screen shows
 * before any group is announced (§1.1). Public screens must read only
 * finalized records.
 *
 * `votes` here is the authoritative aggregate; votes.ts holds a representative
 * sample of individual vote records for the admin voting monitor.
 */

function result(
  id: string,
  cycleId: string,
  subCategoryId: string,
  tier: GroupResult["tier"],
  entryId: string,
  votes: number,
  rank: number | null,
  level: GroupResult["level"],
  options: Partial<GroupResult> = {},
): GroupResult {
  return {
    id,
    cycleId,
    subCategoryId,
    tier,
    entryId,
    votes,
    rank,
    level,
    withheld: false,
    finalized: cycleId !== "cycle-2026",
    finalizedAt: cycleId !== "cycle-2026" ? "2025-08-30T17:00:00Z" : null,
    ...options,
  };
}

