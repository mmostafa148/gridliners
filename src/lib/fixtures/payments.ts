import type { Payment, PricingSnapshot, Tier, PricingWindow } from "@/lib/api/types";

/**
 * Every payment stores a full pricing snapshot (§3.4): window, base price,
 * each sub-category fee, loyalty rule and amount, promo rule and amount, and
 * the final USD total. Quotes are final at checkout — later window changes,
 * cash confirmation or expiry never re-price an already-quoted entry.
 *
 * Tier supplements (§3.3) are linked to the entry and invoiced like any other
 * charge, so one entry can hold multiple payments.
 */

function snapshot(
  tier: Tier,
  window: PricingWindow,
  basePriceUsd: number,
  baseSubCategoryId: string,
  quotedAt: string,
  options: Partial<PricingSnapshot> = {},
): PricingSnapshot {
  const additionalSubCategories = options.additionalSubCategories ?? [];
  const subtotalUsd =
    basePriceUsd + additionalSubCategories.reduce((sum, line) => sum + line.amountUsd, 0);
  const loyalty = options.loyalty ?? null;
  const promo = options.promo ?? null;
  const credit = options.credit ?? null;
  const totalUsd =
    Math.round(
      (subtotalUsd - (loyalty?.amountUsd ?? 0) - (promo?.amountUsd ?? 0)) * 100,
    ) / 100;

  return {
    window,
    tier,
    basePriceUsd,
    baseSubCategoryId,
    additionalSubCategories,
    submissionNumber: options.submissionNumber ?? 1,
    loyalty,
    promo,
    credit,
    subtotalUsd,
    totalUsd,
    quotedAt,
  };
}

