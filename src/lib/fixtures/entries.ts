/**
 * A shortlisted 2026 entry.
 *
 * The six entries above are written out in full because each one also carries a
 * state-machine case the screens need - a paid same-parent add-on, a tier
 * settlement, an Arabic-authored entry. These are the rest of the field: enough
 * finalists in enough groups that the public listing behaves like a real cycle
 * rather than a demo, which is what a page of one-entry groups was.
 *
 * **Every name, title, description and country here is invented placeholder
 * content** and must be replaced before launch, exactly as the six above are.
 * What is *not* placeholder is the shape: the spread across all seven parent
 * categories, the groups of three and four, the mix of authored languages and
 * the tier distribution are what the real thing looks like, and they are what
 * the listing, the filter and the group counts are built and verified against.
 *
 * Dates sit inside the 2026 cycle's own submission windows, verified tier equals
 * declared tier, and every `juryFinalScore` clears its tier's shortlist
 * threshold (55 / 60 / 65) - a shortlisted entry that had not cleared its own
 * bar would contradict the page that publishes it.
 */
function cadet(
  id: string,
  slug: string,
  participantId: string,
  title: string,
  description: string,
  country: string,
  baseSubCategoryId: string,
  tier: Tier,
  juryFinalScore: number,
  options: Partial<EntryInput> = {},
): Entry {
  return makeEntry({
    id,
    slug,
    cycleId: "cycle-2026",
    participantId,
    state: "shortlisted",
    title,
    description,
    country,
    declaredTier: tier,
    baseSubCategoryId,
    verifiedTier: tier,
    verifiedAt: "2026-02-25T10:00:00Z",
    createdAt: "2025-12-05T09:00:00Z",
    checkoutCompletedAt: "2025-12-06T09:00:00Z",
    submittedAt: "2025-12-06T09:00:00Z",
    paymentIds: [`pay-${id}`],
    juryFinalScore,
    ...options,
  });
}

