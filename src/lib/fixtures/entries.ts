/**
 * Entries covering EVERY state in the §3.7 machine, plus the settlement,
 * re-categorization and multi-sub-category paths.
 *
 * Cycle 2026 (active, Voting phase) carries the live states; cycle 2025
 * (archived) carries the finalized result set that the winners and finalists
 * pages read; cycle 2024 gives the year archive a second entry point.
 *
 * Media URLs point at local placeholders — real photography comes from the
 * client (CLAUDE.md).
 */

interface EntryInput {
  id: string;
  slug: string;
  cycleId: string;
  participantId: string;
  state: EntryState;
  title: string;
  description: string;
  contentLanguage?: ContentLanguage;
  country: string;
  credits?: string[];
  externalUrl?: string;
  client?: string;
  videoUrl?: string;
  declaredTier: Tier;
  baseSubCategoryId: string;
  additionalSubCategoryIds?: string[];
  verifiedTier?: Tier;
  verifiedAt?: string | null;
  settlement?: Settlement | null;
  corrections?: TierCorrection[];
  categoryMove?: CategoryMove | null;
  createdAt: string;
  checkoutCompletedAt?: string | null;
  submittedAt?: string | null;
  paymentIds?: string[];
  juryFinalScore?: number | null;
  disqualificationId?: string;
}

function makeEntry(input: EntryInput): Entry {
  const tierForProof = input.verifiedTier ?? input.declaredTier;

  return {
    id: input.id,
    slug: input.slug,
    cycleId: input.cycleId,
    participantId: input.participantId,
    state: input.state,
    title: input.title,
    description: input.description,
    contentLanguage: input.contentLanguage ?? "en",
    country: input.country,
    credits: input.credits ?? [],
    ...(input.externalUrl ? { externalUrl: input.externalUrl } : {}),
    ...(input.client ? { client: input.client } : {}),
    media: {
      coverUrl: `/placeholders/${input.slug}-cover.jpg`,
      galleryUrls: [
        `/placeholders/${input.slug}-01.jpg`,
        `/placeholders/${input.slug}-02.jpg`,
        `/placeholders/${input.slug}-03.jpg`,
      ],
      documentUrls: [],
      ...(input.videoUrl ? { videoUrl: input.videoUrl } : {}),
    },
    declaredTier: input.declaredTier,
    baseSubCategoryId: input.baseSubCategoryId,
    additionalSubCategoryIds: input.additionalSubCategoryIds ?? [],
    eligibilityProof: {
      tier: tierForProof,
      ...(tierForProof === "students"
        ? { studentId: `STU-${input.id.toUpperCase()}`, university: "American University of Sharjah" }
        : tierForProof === "freelancers"
          ? { portfolioUrl: `https://portfolio.example/${input.slug}`, freelanceLicence: `FL-${input.id.toUpperCase()}` }
          : { companyName: input.title.split(" ")[0], tradeLicence: `TL-${input.id.toUpperCase()}` }),
      // Proofs are Admin-only and purged after the cycle plus a retention
      // window (placeholder: 6 months) — §3.6.
      retentionUntil: "2027-02-15T00:00:00Z",
    },
    verification:
      input.verifiedTier || input.settlement || input.verifiedAt !== undefined
        ? {
            declaredTier: input.declaredTier,
            verifiedTier: input.verifiedTier ?? input.declaredTier,
            actor: "admin@gridliners.com",
            verifiedAt: input.verifiedAt ?? null,
            corrections: input.corrections ?? [],
            settlement: input.settlement ?? null,
          }
        : null,
    categoryMove: input.categoryMove ?? null,
    createdAt: input.createdAt,
    checkoutCompletedAt: input.checkoutCompletedAt ?? null,
    submittedAt: input.submittedAt ?? null,
    paymentIds: input.paymentIds ?? [],
    juryFinalScore: input.juryFinalScore ?? null,
    ...(input.disqualificationId ? { disqualificationId: input.disqualificationId } : {}),
  };
}

