/**
 * A provisional client for every public project.
 *
 * **The Sitemap maps Project Client as an element of the page, so a public
 * project has to carry one.** Four of the 390 did: the ones with hand-written
 * story data. The rest showed nothing, because until now nothing in the model
 * held a client at all.
 *
 * These names are **stand-ins, exactly like the drawn galleries and the four
 * narrative movements**, and they are registered as provisional in
 * `docs/temporary-media.md` for replacement by the client's real records. They
 * are derived rather than random so a project's client is the same name on
 * every render, in every locale, in the share card and on the page.
 *
 * An Arabic entry gets an Arabic client: the descriptor leads the name the way
 * it does in Arabic organisation names, rather than a Latin word bolted onto an
 * Arabic title.
 */
const CLIENT_SUFFIX = [
  "Group",
  "Foundation",
  "Trading",
  "Holdings",
  "Company",
  "Partners",
  "Collective",
  "Industries",
] as const;

const CLIENT_PREFIX_AR = ["مجموعة", "مؤسسة", "شركة", "دار", "مركز"] as const;

/**
 * Words that describe the work rather than name the organisation.
 *
 * An Arabic project title usually leads with what was made - "هوية معرض
 * الرياض" is "the identity of the Riyadh exhibition" - so composing a client
 * straight from the title produced "the Foundation of the identity of the
 * Riyadh exhibition". Dropping the leading descriptor leaves the name itself.
 */
const WORK_WORDS_EN = new Set([
  "logo",
  "identity",
  "rebrand",
  "redesign",
  "packaging",
  "study",
  "campaign",
  "book",
  "poster",
  "film",
  "app",
  "site",
  "mark",
  "system",
  "brand",
  "type",
  "cover",
]);

const WORK_WORDS_AR = new Set([
  "هوية",
  "دراسة",
  "تجديد",
  "تصميم",
  "إعادة",
  "حملة",
  "غلاف",
  "شعار",
]);

function slugSeed(slug: string): number {
  let h = 0;
  for (let i = 0; i < slug.length; i += 1) h = (h * 31 + slug.charCodeAt(i)) >>> 0;
  return h;
}

function provisionalClient(entry: Entry): string {
  const seed = slugSeed(entry.slug);
  if (entry.contentLanguage === "ar") {
    const words = entry.title.split(/\s+/);
    while (words.length > 1 && WORK_WORDS_AR.has(words[0])) words.shift();
    return `${CLIENT_PREFIX_AR[seed % CLIENT_PREFIX_AR.length]} ${words.join(" ")}`;
  }
  // English titles name the work at the end - "Solace Logo", "Anfa Atlas Book"
  // - so the trailing descriptor goes before the organisation word is added,
  // or the client reads "Solace Logo Partners". Two words is then enough to
  // name an organisation without turning a long title into a sentence.
  const words = entry.title.split(/\s+/);
  while (words.length > 1 && WORK_WORDS_EN.has(words[words.length - 1].toLowerCase())) {
    words.pop();
  }
  const stem = words.slice(0, 2).join(" ");
  return `${stem} ${CLIENT_SUFFIX[seed % CLIENT_SUFFIX.length]}`;
}

