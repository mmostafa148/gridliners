/**
 * A public slug is an address, so two public entries may not share one.
 *
 * Four did - `kite-mark` across two cycles, and `lowtide-sequence-1..3` twice
 * inside 2026 - which meant `generateStaticParams` emitted 390 slugs of which
 * only 386 were distinct, and four shortlisted projects had no page at all:
 * their URL served the other project's work, title and country. Found by the
 * element sweep in §23, not by a route test, because both URLs answered 200.
 *
 * Development throws rather than warns, for the same reason a missing message
 * does: this is a defect, and it is invisible until someone looks for it.
 */
if (process.env.NODE_ENV !== "production") {
  const seen = new Set<string>();
  for (const entry of entriesInOrder) {
    if (entry.state !== "shortlisted") continue;
    if (seen.has(entry.slug)) {
      throw new Error(`Duplicate public slug in fixtures: ${entry.slug}`);
    }
    seen.add(entry.slug);
  }
}

/**
 * A provisional address and film for every public project.
 *
 * The Sitemap marks both as conditional, and the fixtures honoured that
 * literally: **two** of the 390 carried a link and **one** carried a film, so
 * the two rows were invisible on effectively every page and the client could
 * not review them. They are now on all 390, stand-ins like the galleries, the
 * narratives and the client names, and registered with them in
 * `docs/temporary-media.md`.
 *
 * **`example.com` is deliberate, and it is reserved for exactly this by
 * RFC 2606.** These addresses do not resolve and are not meant to: pointing a
 * placeholder at a real host would send a reader to somebody else's page, or to
 * a 404 on a service that has nothing to do with this project.
 *
 * The conditional rendering stays. The fields are optional on `Entry` because a
 * real entrant may have neither, and `ProjectRecord` still omits each row on
 * its own - the fixtures simply no longer exercise the empty case for these
 * two. `credits`, which 6 of 390 carry, still does.
 */
function provisionalLink(entry: Entry): string {
  const stem = entry.slug.split("-")[0];
  return `https://${stem}.example.com/${entry.slug}`;
}

function provisionalFilm(entry: Entry): string {
  return `https://films.example.com/${entry.slug}`;
}

